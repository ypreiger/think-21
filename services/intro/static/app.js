let lang = "en";
let me = null;
let config = { google: false, linkedin: false, questionnaireUrl: "" };
const params = new URLSearchParams(location.search);

function t() { return T[lang]; }

function applyDir() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
  document.getElementById("title").textContent = t().title;
  document.getElementById("langs").innerHTML = ["en", "ru", "he"].map((code) => {
    const name = { en: "English", ru: "Русский", he: "עברית" }[code];
    return `<button type="button" data-lang="${code}" class="${code === lang ? "on" : ""}">${name}</button>`;
  }).join("");
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.onclick = () => { lang = button.dataset.lang; render(); };
  });
}

function render() {
  applyDir();
  const notice = params.get("auth") === "failed" ? `<p class="notice">${t().failed}</p>` : "";
  const ready = config.linkedin || config.google;
  const setup = !ready ? `<p class="notice">${t().unconfigured}</p>` : "";
  let side = "";
  if (!me) {
    side = `
      <aside class="panel">
        <h2>${t().signTitle}</h2>
        ${notice}${setup}
        <div class="signin">
          <a class="linkedin" href="/auth/linkedin">${t().linkedin}</a>
          <a class="google" href="/auth/google">${t().google}</a>
        </div>
      </aside>`;
  } else if (!me.consentAt) {
    side = `
      <aside class="panel">
        <h2>${t().signed}</h2>
        <p>${escapeHtml(me.name || me.email)}</p>
        <p class="muted">${escapeHtml(me.email)}</p>
        ${notice}
        <label class="consent"><input id="accepted" type="checkbox"> <span>${t().consent}</span></label>
        <button class="primary" id="agree" type="button">${t().agree}</button>
        <form method="post" action="/api/logout"><button class="quiet" type="submit">${t().signOut}</button></form>
      </aside>`;
  } else {
    const href = `${config.questionnaireUrl}/?id=${encodeURIComponent(me.participantId)}&lang=${lang}`;
    side = `
      <aside class="panel">
        <h2>${t().signed}</h2>
        <p>${escapeHtml(me.name || me.email)}</p>
        <p class="kicker">${t().yourId}</p>
        <p class="id">${escapeHtml(me.participantId)}</p>
        <a class="linkedin" id="open" href="${href}" target="_blank" rel="noopener">${t().open}</a>
        <form method="post" action="/api/logout"><button class="quiet" type="submit">${t().signOut}</button></form>
      </aside>`;
  }
  document.getElementById("app").innerHTML = `
    <div class="layout">
      <article class="card">
        <h1>${t().heading}</h1>
        <p class="lede">${t().lede}</p>
        <div class="facts">
          <div class="fact"><strong>${t().whoTitle}</strong>${t().who}</div>
          <div class="fact"><strong>${t().timeTitle}</strong>${t().time}</div>
        </div>
        <h2>${t().ethicsTitle}</h2>
        <p>${t().ethics}</p>
        <h2>${t().howTitle}</h2>
        <ol class="steps">${t().steps.map((step) => `<li>${step}</li>`).join("")}</ol>
      </article>
      ${side}
    </div>`;
  const agree = document.getElementById("agree");
  if (agree) agree.onclick = accept;
  const open = document.getElementById("open");
  if (open) open.onclick = (event) => {
    event.preventDefault();
    saveLangAndOpen(open.href);
  };
}

async function accept() {
  const box = document.getElementById("accepted");
  if (!box.checked) {
    box.focus();
    return;
  }
  const response = await fetch("/api/consent", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ accepted: true, lang })
  });
  if (response.ok) {
    me = await response.json();
    render();
  }
}

async function saveLangAndOpen(href) {
  await fetch("/api/consent", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ accepted: true, lang })
  });
  window.open(href, "_blank", "noopener");
}

function escapeHtml(value) {
  return String(value || "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

async function boot() {
  config = await (await fetch("/api/config")).json();
  const response = await fetch("/api/me");
  if (response.ok) {
    me = await response.json();
    if (["en", "ru", "he"].includes(me.lang)) lang = me.lang;
  }
  render();
}

boot();
